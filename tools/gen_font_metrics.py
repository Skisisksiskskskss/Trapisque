#!/usr/bin/env python3
"""
Generate tests/fake/fonts.luau: how wide each character is in the game's fonts, so the
fake Roblox (tests/fake/roblox.luau) measures text (TextBounds, AutomaticSize) the way
Roblox does and the screenshots lay out like the real thing.

Usage:
    python3 tools/gen_font_metrics.py [FONT_DIR]   (default: $TRAPISQUE_FONTS or tools/preview/fonts)

Re-run it when the game starts using another font.
"""
import os
import sys

from PIL import ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "fake", "fonts.luau")

# family -> (file, weights to measure (variable fonts), or None for a single weight)
FONTS = {
    "LuckiestGuy": ("LuckiestGuy-Regular.ttf", None),
    "Nunito": ("Nunito[wght].ttf", {"Regular": 400, "Medium": 500, "SemiBold": 600, "Bold": 700, "ExtraBold": 800, "Heavy": 900}),
    "FredokaOne": ("FredokaOne-Regular.ttf", None),
    "Bangers": ("Bangers-Regular.ttf", None),
    "Oswald": ("Oswald[wght].ttf", {"Regular": 400, "Medium": 500, "SemiBold": 600, "Bold": 700}),
    "SpecialElite": ("SpecialElite-Regular.ttf", None),
    "PatrickHand": ("PatrickHand-Regular.ttf", None),
    "PirataOne": ("PirataOne-Regular.ttf", None),
    "Rye": ("Rye-Regular.ttf", None),
    "Merriweather": ("Merriweather[opsz,wdth,wght].ttf", {"Regular": 400, "Bold": 700, "Heavy": 900}),
}
SIZE = 100


def measure(path, weight):
    f = ImageFont.truetype(path, SIZE)
    if weight is not None:
        axes = f.get_variation_axes()
        vals = []
        for ax in axes:
            nm = ax.get("name", b"")
            nm = nm.decode() if isinstance(nm, bytes) else str(nm)
            if nm.lower().startswith("weight") or nm == "wght":
                vals.append(max(ax["minimum"], min(ax["maximum"], weight)))
            else:
                vals.append(ax.get("default", ax["minimum"]))
        f.set_variation_by_axes(vals)
    widths = [round(f.getlength(chr(c)) / SIZE, 3) for c in range(32, 127)]
    asc, desc = f.getmetrics()
    return widths, round((asc + desc) / SIZE, 3)


def main():
    font_dir = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("TRAPISQUE_FONTS", os.path.join(ROOT, "tools", "preview", "fonts"))
    lines = [
        "-- AUTO-GENERATED by tools/gen_font_metrics.py: character widths (per 1 of TextSize) for",
        "-- printable ASCII (32-126) in the game's fonts. Do not edit; re-run the script.",
        "FAKE_FONTS = {",
    ]
    for family, (file, weights) in FONTS.items():
        path = os.path.join(font_dir, file)
        if not os.path.exists(path) or os.path.getsize(path) < 1000:
            print("skipping", family, "(no", file + ")")
            continue
        lines.append("\t%s = {" % family)
        for wname, wval in (weights or {"Regular": None}).items():
            widths, line = measure(path, wval)
            lines.append("\t\t%s = { line = %s, w = { %s } }," % (wname, line, ", ".join("%g" % w for w in widths)))
        lines.append("\t},")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
